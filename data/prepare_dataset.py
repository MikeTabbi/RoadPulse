"""
RoadPulse - Dataset Preparation Script
Converts RDD2022 from PASCAL VOC (XML) format to YOLOv8 (TXT) format
and splits into train/val sets.

Usage:
    python data/prepare_dataset.py --rdd2022 "C:\\Users\\Michael\\dev\\RDD2022\\RDD2022" --output "C:\\Users\\Michael\\dev\\RoadPulse\\data\\rdd2022_yolo"
"""

import os
import glob
import random
import shutil
import argparse
from pathlib import Path
import bs4 as bs
from tqdm import tqdm


# RDD2022 damage classes (we only use the 4 main classes)
CLASS_MAP = {
    "D00": 0,  # Longitudinal Crack
    "D10": 1,  # Transverse Crack
    "D20": 2,  # Alligator Crack
    "D40": 3,  # Pothole
}

# Countries and their annotation paths relative to RDD2022 root
COUNTRY_PATHS = [
    "Japan/train",
    "India/train",
    "Czech/train",
    "United_States/United_States/train",
]


def convert_voc_to_yolo(xml_path):
    """Convert a single PASCAL VOC XML annotation to YOLO format."""
    with open(xml_path, "r") as f:
        soup = bs.BeautifulSoup(f.read(), "xml")

    size = soup.find("size")
    img_w = int(size.find("width").text)
    img_h = int(size.find("height").text)

    annotations = []
    for obj in soup.find_all("object"):
        class_name = obj.find("name").text

        if class_name not in CLASS_MAP:
            continue

        class_id = CLASS_MAP[class_name]

        xmin = float(obj.find("xmin").text)
        ymin = float(obj.find("ymin").text)
        xmax = float(obj.find("xmax").text)
        ymax = float(obj.find("ymax").text)

        w = (xmax - xmin) / img_w
        h = (ymax - ymin) / img_h
        cx = (xmin + (xmax - xmin) / 2) / img_w
        cy = (ymin + (ymax - ymin) / 2) / img_h

        annotations.append(f"{class_id} {cx:.4f} {cy:.4f} {w:.4f} {h:.4f}")

    return annotations


def prepare_dataset(rdd2022_root, output_dir, val_split=0.15, seed=42):
    """Main pipeline: convert annotations, pair with images, split train/val."""

    random.seed(seed)

    for split in ["train", "val"]:
        os.makedirs(os.path.join(output_dir, split, "images"), exist_ok=True)
        os.makedirs(os.path.join(output_dir, split, "labels"), exist_ok=True)

    pairs = []
    skipped = 0

    for country_path in COUNTRY_PATHS:
        xml_dir = os.path.join(rdd2022_root, country_path, "annotations", "xmls")
        img_dir = os.path.join(rdd2022_root, country_path, "images")

        if not os.path.exists(xml_dir):
            print(f"WARNING: Path not found, skipping: {xml_dir}")
            continue

        xml_files = sorted(glob.glob(os.path.join(xml_dir, "*.xml")))
        country_name = country_path.split("/")[0]
        print(f"Processing {country_name}: {len(xml_files)} annotations...")

        for xml_path in tqdm(xml_files, desc=country_name):
            yolo_annots = convert_voc_to_yolo(xml_path)

            if not yolo_annots:
                skipped += 1
                continue

            xml_name = os.path.basename(xml_path)
            img_name = xml_name.replace(".xml", ".jpg")
            img_path = os.path.join(img_dir, img_name)

            if not os.path.exists(img_path):
                img_name = xml_name.replace(".xml", ".png")
                img_path = os.path.join(img_dir, img_name)
                if not os.path.exists(img_path):
                    skipped += 1
                    continue

            pairs.append((img_path, img_name, yolo_annots))

    print(f"\nTotal valid pairs: {len(pairs)}")
    print(f"Skipped (no annotations or missing image): {skipped}")

    random.shuffle(pairs)
    val_count = int(len(pairs) * val_split)
    val_pairs = pairs[:val_count]
    train_pairs = pairs[val_count:]

    print(f"Train: {len(train_pairs)} | Val: {len(val_pairs)}")

    for split_name, split_pairs in [("train", train_pairs), ("val", val_pairs)]:
        print(f"\nCopying {split_name} set...")
        for img_path, img_name, yolo_annots in tqdm(split_pairs, desc=split_name):
            dst_img = os.path.join(output_dir, split_name, "images", img_name)
            shutil.copy2(img_path, dst_img)

            label_name = img_name.rsplit(".", 1)[0] + ".txt"
            dst_label = os.path.join(output_dir, split_name, "labels", label_name)
            with open(dst_label, "w") as f:
                f.write("\n".join(yolo_annots))

    yaml_content = f"""# RDD2022 Dataset Config for YOLOv8
# Auto-generated by RoadPulse prepare_dataset.py

path: {output_dir}
train: train/images
val: val/images

names:
  0: D00_Longitudinal_Crack
  1: D10_Transverse_Crack
  2: D20_Alligator_Crack
  3: D40_Pothole

# Dataset stats:
# Train images: {len(train_pairs)}
# Val images: {len(val_pairs)}
# Classes: 4
"""
    yaml_path = os.path.join(output_dir, "rdd2022.yaml")
    with open(yaml_path, "w") as f:
        f.write(yaml_content)

    print(f"\nDataset YAML saved to: {yaml_path}")
    print("Done! Ready for training.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Prepare RDD2022 for YOLOv8 training")
    parser.add_argument("--rdd2022", type=str, required=True, help="Path to RDD2022 root folder")
    parser.add_argument("--output", type=str, required=True, help="Output directory for YOLO-formatted dataset")
    parser.add_argument("--val_split", type=float, default=0.15, help="Validation split ratio (default: 0.15)")
    args = parser.parse_args()

    prepare_dataset(args.rdd2022, args.output, args.val_split)
